def main() -> int:
    tombs = load_tombstone_hosts(TOMB)
    seed = load_seed(SEED)
    tracker_suffixes = load_tracker_suffixes(TRACKER_MAP)
    domains, suffixes, reject_kw, safe_list = build_interest(seed)
    # Merge tracker into matching set (also available separately for README)
    apps = parse_catalog_interest_apps(CATALOG)

    print(f"catalog surge_interest apps: {len(apps)}")
    print(
        f"seed domains={len(domains)} suffixes={len(suffixes)} "
        f"reject_kw={len(reject_kw)} safe_kw={len(safe_list)} "
        f"tracker_suffixes={len(tracker_suffixes)}"
    )
    print(f"tombstone hosts: {sorted(tombs)}")
    print(f"banned naked needles: {sorted(BANNED_NAKED_NEEDLES)}")

    results = []
    for name in DOMAINSET_FILES:
        src = SKK / "domainset" / name
        dst = OWNED / "domainset" / name
        is_phish = name == "reject_phishing.conf"
        hdr = HEADER_PHISHING if is_phish else HEADER_DOMAINSET
        src_n, kept, th = rebuild_file(
            src,
            dst,
            hdr,
            True,
            tombs,
            domains,
            suffixes,
            tracker_suffixes,
            reject_kw,
            safe_list,
            phishing=is_phish,
        )
        size = dst.stat().st_size
        results.append(("domainset/" + name, src_n, kept, th, size))
        print(f"  domainset/{name}: {src_n} -> {kept} (tomb {th}) {size} bytes")

    for name in NON_IP_FILES:
        src = SKK / "non_ip" / name
        dst = OWNED / "non_ip" / name
        src_n, kept, th = rebuild_file(
            src,
            dst,
            HEADER_NON_IP,
            False,
            tombs,
            domains,
            suffixes,
            tracker_suffixes,
            reject_kw,
            safe_list,
        )
        size = dst.stat().st_size
        results.append(("non_ip/" + name, src_n, kept, th, size))
        print(f"  non_ip/{name}: {src_n} -> {kept} (tomb {th}) {size} bytes")

    write_owned_readme(apps, tracker_suffixes, tombs)
    print(f"wrote {OWNED_README}")

    # verify no tombstones remain
    bad = []
    for kind, name in [("domainset", n) for n in DOMAINSET_FILES] + [
        ("non_ip", n) for n in NON_IP_FILES
    ]:
        text = (OWNED / kind / name).read_text(encoding="utf-8").lower()
        for t in tombs:
            tb = t.lstrip(".")
            for ln in text.splitlines():
                if ln.startswith("#"):
                    continue
                if kind == "domainset":
                    if ln.strip().lstrip(".") == tb:
                        bad.append((kind, name, t, ln))
                else:
                    if re.search(rf",(?:\.)?{re.escape(tb)}(?:[,\s]|$)", ln):
                        bad.append((kind, name, t, ln))
    if bad:
        print("ERROR: tombstones still present:", bad[:10], file=sys.stderr)
        return 1
    print("tombstone check: clean")
    return 0


