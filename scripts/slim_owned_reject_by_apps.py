def load_tombstone_hosts(path: Path) -> set[str]:
    hosts: set[str] = set()
    if not path.exists():
        raise SystemExit(f"missing {path}")
    in_ds = False
    for ln in path.read_text(encoding="utf-8").splitlines():
        s = ln.strip()
        if s.startswith("reject_domainset:"):
            in_ds = True
            continue
        if in_ds:
            if s.startswith("-"):
                v = s[1:].strip().strip('"').strip("'")
                if v:
                    hosts.add(v.lower())
                    hosts.add(v.lstrip(".").lower())
            elif s and not s.startswith("#") and ":" in s and not s.startswith("-"):
                break
    return hosts


def load_seed(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def load_tracker_suffixes(path: Path) -> set[str]:
    """Parse app_tracker_map.yaml keep_suffixes without PyYAML."""
    suffixes: set[str] = set()
    if not path.exists():
        raise SystemExit(f"missing {path}")
    in_keep = False
    for ln in path.read_text(encoding="utf-8").splitlines():
        raw = ln.rstrip()
        s = raw.strip()
        if s.startswith("keep_suffixes:"):
            in_keep = True
            continue
        if in_keep:
            if s.startswith("-"):
                v = s[1:].strip().strip('"').strip("'")
                if v:
                    suffixes.add(v.lstrip(".").lower())
                continue
            # end of list when indentation drops to key level or new app field
            if s.startswith("#"):
                continue
            if s and not s.startswith("-"):
                in_keep = False
    return suffixes


def etld1(host: str) -> str:
    h = host.lstrip(".").lower()
    parts = h.split(".")
    if len(parts) < 2:
        return h
    if len(parts) >= 3 and ".".join(parts[-2:]) in MULTI_PART_PUBLIC:
        return ".".join(parts[-3:])
    return ".".join(parts[-2:])


def parent_chain(host: str) -> list[str]:
    parts = host.lstrip(".").lower().split(".")
    return [".".join(parts[i:]) for i in range(len(parts))]


def host_equals_or_ends_with(host: str, suffix: str) -> bool:
    """Full-label suffix match: h == s OR h.endswith('.'+s)."""
    h = host.lstrip(".").lower()
    s = suffix.lstrip(".").lower()
    if not h or not s:
        return False
    return h == s or h.endswith("." + s)


def wordish_label_match(host: str, token: str) -> bool:
    """True if token appears as whole label or label prefix/suffix (not mid-string)."""
    tok = token.lower().strip(".")
    if not tok:
        return False
    h = host.lstrip(".").lower()
    for lab in h.split("."):
        if not lab:
            continue
        if lab == tok or lab.startswith(tok) or lab.endswith(tok):
            return True
        # hyphen-separated: foo-tok-bar
        parts = lab.split("-")
        if tok in parts:
            return True
    return False


def is_banned_needle(n: str) -> bool:
    nn = n.strip().lower()
    if not nn:
        return True
    if nn in BANNED_NAKED_NEEDLES:
        return True
    if len(nn) <= 5:
        return True
    return False


def build_interest(seed: dict) -> tuple[set[str], set[str], set[str], list[str]]:
    """Return domains, suffixes, reject_kw (undotted), safe_kw_list for KEYWORD rules."""
    domains = {d.lstrip(".").lower() for d in seed.get("domains", []) if d}
    suffixes = {s.lstrip(".").lower() for s in seed.get("suffixes", []) if s}
    reject_kw: set[str] = set()

    for x in seed.get("reject_interest", []) or []:
        xx = str(x).strip().lstrip(".").lower()
        if not xx:
            continue
        if "." in xx:
            suffixes.add(xx)
            domains.add(xx)
        else:
            # undotted reject_interest (e.g. pangolin) — word-ish only, never bare ≤5
            if not is_banned_needle(xx):
                reject_kw.add(xx)

    for w in seed.get("wildcards", []) or []:
        ww = str(w).strip().lstrip(".").lower()
        m = re.search(r"\*\.([a-z0-9.-]+\.[a-z]{2,})$", ww)
        if m:
            suffixes.add(m.group(1))
        elif "*." in ww:
            base = ww.split("*.", 1)[-1]
            if base and "." in base:
                suffixes.add(base)

    # Safe long keywords for DOMAIN-KEYWORD only (never for domainset substring).
    safe: set[str] = set(SAFE_LONG_KEYWORDS)
    for key in ("keywords", "vendors"):
        for v in seed.get(key, []) or []:
            vv = str(v).strip().lower()
            if is_banned_needle(vv):
                continue
            if len(vv) >= 6:
                safe.add(vv)
    for x in seed.get("reject_interest", []) or []:
        xx = str(x).strip().lstrip(".").lower()
        if xx and "." not in xx and not is_banned_needle(xx):
            safe.add(xx)

    safe_list = sorted(safe, key=len, reverse=True)
    return domains, suffixes, reject_kw, safe_list


def is_tombstoned(host: str, tombs: set[str]) -> bool:
    h = host.lstrip(".").lower()
    return h in tombs or host.lower() in tombs


def host_of_interest(
    host: str,
    domains: set[str],
    suffixes: set[str],
    tracker_suffixes: set[str],
    reject_kw: set[str],
) -> bool:
    """Keep host if seed domain/suffix OR tracker map OR reject_interest wordish."""
    h = host.lstrip(".").lower()
    if not h:
        return False
    for p in parent_chain(h):
        if p in domains or p in suffixes:
            return True
    for s in suffixes | domains | tracker_suffixes:
        if host_equals_or_ends_with(h, s):
            return True
    for kw in reject_kw:
        if wordish_label_match(h, kw):
            return True
    return False


def phishing_brand_hit(host: str) -> bool:
    h = host.lstrip(".").lower()
    if not h:
        return False
    for brand in PHISHING_BRANDS:
        if wordish_label_match(h, brand):
            return True
    return False


def parse_catalog_interest_apps(path: Path) -> list[tuple[str, str]]:
    text = path.read_text(encoding="utf-8")
    apps: list[dict] = []
    current: dict | None = None
    for line in text.splitlines():
        m = re.match(r"^  - name:\s*(.+)$", line)
        if m:
            if current and current.get("name"):
                apps.append(current)
            current = {
                "name": m.group(1).strip().strip('"').strip("'"),
                "folder": "(未分组)",
                "surge_interest": False,
            }
            continue
        if current is None:
            continue
        m2 = re.match(r"^    folder:\s*(.+)$", line)
        if m2:
            current["folder"] = m2.group(1).strip().strip('"').strip("'")
        m3 = re.match(r"^    surge_interest:\s*(true|false)\s*$", line)
        if m3:
            current["surge_interest"] = m3.group(1) == "true"
    if current and current.get("name"):
        apps.append(current)
    return [
        (a.get("folder") or "(未分组)", a["name"])
        for a in apps
        if a.get("surge_interest")
    ]


_DOMAIN_RULE = re.compile(
    r"^(DOMAIN|DOMAIN-SUFFIX|DOMAIN-WILDCARD|DOMAIN-KEYWORD),([^,\s]+)(.*)$",
    re.I,
)


def keyword_allowed(val: str, safe_list: list[str]) -> bool:
    """DOMAIN-KEYWORD: length≥6 and matches safe keyword with word-ish boundary."""
    v = val.lower().strip()
    if len(v) < 6:
        return False
    for kw in safe_list:
        if len(kw) < 6:
            continue
        if v == kw:
            return True
        # word-ish: keyword as substring with non-alnum boundaries or ends
        if re.search(
            rf"(^|[^a-z0-9]){re.escape(kw)}([^a-z0-9]|$)", v
        ) or v.startswith(kw) or v.endswith(kw):
            return True
        # also allow if keyword contains the value as full token (rare)
        if kw == v:
            return True
    return False


def filter_domainset_line(
    line: str,
    tombs: set[str],
    domains: set[str],
    suffixes: set[str],
    tracker_suffixes: set[str],
    reject_kw: set[str],
    *,
    phishing: bool = False,
) -> str | None:
    s = line.strip()
    if not s or s.startswith("#"):
        return None
    host = s
    bare = host.lstrip(".")
    if is_tombstoned(bare, tombs) or is_tombstoned(host, tombs):
        return None
    if phishing:
        return s if phishing_brand_hit(bare) else None
    if host_of_interest(bare, domains, suffixes, tracker_suffixes, reject_kw):
        return s
    return None


def filter_non_ip_line(
    line: str,
    tombs: set[str],
    domains: set[str],
    suffixes: set[str],
    tracker_suffixes: set[str],
    reject_kw: set[str],
    safe_list: list[str],
) -> str | None:
    raw = line.rstrip("\n")
    s = raw.strip()
    if not s or s.startswith("#"):
        return None
    m = _DOMAIN_RULE.match(s)
    if not m:
        # IP-CIDR / URL-REGEX / other — keep (rare; not substring-noise)
        return s
    kind = m.group(1).upper()
    value = m.group(2).strip()
    if kind == "DOMAIN-KEYWORD":
        if keyword_allowed(value, safe_list):
            return s
        return None
    # DOMAIN / DOMAIN-SUFFIX / DOMAIN-WILDCARD
    host_clean = re.sub(r"^\*\.", "", value).replace("*", "").strip(".")
    check = host_clean
    if not check:
        return None
    if is_tombstoned(check, tombs):
        return None
    if kind == "DOMAIN-WILDCARD" and "*" in value and "." not in value.replace("*", ""):
        # pure keyword-like wildcard — treat as keyword
        kw = value.replace("*", "").lower()
        if keyword_allowed(kw, safe_list):
            return s
        return None
    if host_of_interest(check, domains, suffixes, tracker_suffixes, reject_kw):
        return s
    return None


def rebuild_file(
    src: Path,
    dst: Path,
    header: str,
    is_domainset: bool,
    tombs: set[str],
    domains: set[str],
    suffixes: set[str],
    tracker_suffixes: set[str],
    reject_kw: set[str],
    safe_list: list[str],
    *,
    phishing: bool = False,
) -> tuple[int, int, int]:
    if not src.exists():
        raise SystemExit(f"missing source {src}")
    kept_lines: list[str] = []
    src_rules = 0
    kept = 0
    tomb_hits = 0
    for ln in src.read_text(encoding="utf-8").splitlines():
        s = ln.strip()
        if not s or s.startswith("#"):
            continue
        src_rules += 1
        if is_domainset:
            bare = s.lstrip(".")
            if is_tombstoned(bare, tombs) or is_tombstoned(s, tombs):
                tomb_hits += 1
                continue
            out = filter_domainset_line(
                ln,
                tombs,
                domains,
                suffixes,
                tracker_suffixes,
                reject_kw,
                phishing=phishing,
            )
        else:
            m = _DOMAIN_RULE.match(s)
            if m:
                val = m.group(2).strip()
                check = re.sub(r"^\*\.", "", val).replace("*", "").strip(".")
                if check and is_tombstoned(check, tombs):
                    tomb_hits += 1
                    continue
            out = filter_non_ip_line(
                ln,
                tombs,
                domains,
                suffixes,
                tracker_suffixes,
                reject_kw,
                safe_list,
            )
        if out is not None:
            kept_lines.append(out)
            kept += 1
    dst.parent.mkdir(parents=True, exist_ok=True)
    body = "\n".join(kept_lines)
    text = header + ("\n" if not header.endswith("\n") else "") + body
    if body:
        text += "\n"
    dst.write_text(text, encoding="utf-8")
    return src_rules, kept, tomb_hits


